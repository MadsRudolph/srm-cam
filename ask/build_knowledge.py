"""Build the assistant's knowledge from the guide.

Reads every page of the guide (website/*.html) in menu order, plus the
in-app reference (docs/usage.md), and writes knowledge.js: one string the
Worker sends as its cached system prompt. Each page starts with its URL and
each section with its #anchor, so answers can link the exact place.

    python ask/build_knowledge.py        # then: cd ask && npx wrangler deploy

Run it after every change to the guide, so the assistant knows what the guide
says.
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "website"
BASE = "https://madsrudolph.github.io/srm-cam/"
SKIP = {"media-plan.html", "feedback.html"}


def menu_order():
    """The pages in the order the guide's menu lists them."""
    nav = re.search(r"<nav>(.*?)</nav>", (SITE / "index.html").read_text(), re.S)
    order = re.findall(r'href="([a-z0-9-]+\.html)"', nav.group(1)) if nav else []
    rest = sorted(p.name for p in SITE.glob("*.html") if p.name not in order)
    return [p for p in order + rest if p not in SKIP]


def page_text(name):
    s = (SITE / name).read_text()
    title = re.search(r"<title>(.*?)</title>", s, re.S)
    title = html.unescape(title.group(1)).split(" — ")[0] if title else name
    s = s[s.find('<div class="content">'):] if '<div class="content">' in s else s
    s = re.sub(r"<(script|style|svg)[^>]*>.*?</\1>", "", s, flags=re.S)
    s = re.sub(r'<footer class="site">.*?</footer>', "", s, flags=re.S)
    s = re.sub(r'<div class="page-nav">.*?</div>\s*</div>?', "", s, flags=re.S)

    def heading(m):
        level, attrs, body = m.group(1), m.group(2), m.group(3)
        anchor = re.search(r'id="([^"]+)"', attrs)
        mark = "#" * int(level)
        link = f" ({BASE}{name}#{anchor.group(1)})" if anchor else ""
        return f"\n\n{mark} {body}{link}\n"
    s = re.sub(r"<h([1-4])([^>]*)>(.*?)</h\1>", heading, s, flags=re.S)
    s = re.sub(r'<span class="st">(.*?)</span>', r"**\1**: ", s, flags=re.S)
    s = re.sub(r'<span class="t">(.*?)</span>', r"[\1] ", s, flags=re.S)
    s = re.sub(r'<span class="(?:ui|menu-path)">(.*?)</span>', r"'\1'", s, flags=re.S)
    s = re.sub(r'<figcaption>(.*?)</figcaption>', r"\n(Figure: \1)\n", s, flags=re.S)
    s = re.sub(r'<img [^>]*alt="([^"]*)"[^>]*>', r"\n(Picture: \1)\n", s)
    s = re.sub(r"<li[^>]*>", "\n- ", s)
    s = re.sub(r"</(p|div|tr|table|ol|ul|figure|li)>", "\n", s)
    s = re.sub(r"<t[dh][^>]*>", " | ", s)
    s = re.sub(r'<a [^>]*href="([^"]+)"[^>]*>(.*?)</a>',
               lambda m: f"{m.group(2)} [{absolute(m.group(1), name)}]", s, flags=re.S)
    s = re.sub(r"</(span|strong|a|em)>", r"</\1> ", s)
    s = html.unescape(re.sub(r"<[^>]+>", "", s))
    s = re.sub(r"[ \t]+", " ", s)
    s = re.sub(r"\n\s*\n\s*\n+", "\n\n", s)
    return title, s.strip()


def absolute(href, page):
    if href.startswith(("http://", "https://", "mailto:")):
        return href
    if href.startswith("#"):
        return f"{BASE}{page}{href}"
    return BASE + href


def main():
    parts = ["# THE SRM-CAM GUIDE", f"The guide lives at {BASE}. Pages in menu order.\n"]
    for name in menu_order():
        title, text = page_text(name)
        parts.append(f"\n\n========== PAGE: {title} — {BASE}{name} ==========\n{text}")
    usage = (ROOT / "docs" / "usage.md").read_text()
    parts.append("\n\n========== APP REFERENCE (docs/usage.md, the in-app Help guide; "
                 "where it disagrees with the guide pages above, the guide pages are newer) "
                 "==========\n" + usage)
    knowledge = "\n".join(parts)
    out = Path(__file__).resolve().parent / "knowledge.js"
    out.write_text("// Generated by build_knowledge.py from website/ and docs/usage.md. "
                   "Do not edit.\nexport default " + json.dumps(knowledge) + ";\n")
    print(f"{out}: {len(knowledge):,} characters, about {len(knowledge) // 4:,} tokens")


if __name__ == "__main__":
    main()
